/**
 * Browser mock of the backend (`pnpm dev:mock`). Serves the fixtures' committed `.gitvur/`
 * files and sources, bundled at build time. URL parameters:
 *
 * - `?fixture=py-small|ts-small` opens that fixture at startup (default: none).
 * - `?state=no-gitvur|schema-invalid|structure-only|indexing` simulates the matching
 *   backend behaviour, for screenshots of each state.
 * - Diffs (Changes lens) for py-small come from `mockDiff.json`, generated from a real
 *   Git scenario by `crates/gitvur-diff/tests/mock_diff.rs`.
 * - `?firstrun=1` shows the first-run guide (otherwise the mock starts as if it was seen).
 * - `?state=lost` makes opening fail as if the folder had been moved or deleted.
 * - `?state=trust` serves hand-crafted validation results (every status and issue code,
 *   see `mockTrust.ts`); `?state=report-stale` a report older than the structure.
 * - `?state=flow-stale|flow-broken` (py-flows): a stale or broken flow, see `flowStateBundle`.
 * - Traces for py-flows and ts-flows come from `mockTraces.json`, generated by the real
 *   `gitvur_flow::trace` in `app/src-tauri/src/trace.rs` (default limits; `depth` and
 *   `maxNodes` are ignored).
 * - `?missing=<relpath>` serves that source file as if it had been deleted after indexing,
 *   for the inspector's missing-source warning.
 */

/** Generated by `pnpm gen:synthetic`; loaded on demand so it never weighs on other fixtures. */
const synthetic = import.meta.glob<RepoBundle>("../../.synthetic/bundle.json", {
  import: "default",
});

const PREFIX = "../../../fixtures/";
const SETTINGS_KEY = "gitvur.mock.settings";
const VIEW_KEY = "gitvur.mock.view:";
const params = new URLSearchParams(window.location.search);
const state = params.get("state");
const missing = params.get("missing");

function fixtureOf(path: string): string {
  return path.replace(/^mock:\/\//, "");
}

function file(fixture: string, name: string): unknown {
  return gitvurFiles[`${PREFIX}${fixture}/.gitvur/${name}`];
}

function fail(code: AppError["code"], message: string, detail?: string): Promise<never> {
  const error: AppError = { code, message };
  if (detail !== undefined) error.detail = detail;
  // Tauri rejects with the serialised AppError object, not an Error; the mock matches it.
  // eslint-disable-next-line @typescript-eslint/prefer-promise-reject-errors
  return Promise.reject(error);
}

async function syntheticBundle(): Promise<RepoBundle> {
  const load = synthetic["../../.synthetic/bundle.json"];
  if (!load)
    return fail("no-gitvur", "Synthetic data not generated", "Run `pnpm gen:synthetic` in app/.");
  return load();
}

function bundle(path: string): Promise<RepoBundle> {
  const fixture = fixtureOf(path);
  if (fixture === "synthetic") return syntheticBundle();
  const manifest = file(fixture, "manifest.json") as Manifest | undefined;
  const structure = file(fixture, "structure.json") as Structure | undefined;
  if (state === "lost") {
    return fail(
      "not-a-directory",
      `${path} does not exist`,
      "No such file or directory (os error 2)",
    );
  }
  if (state === "no-gitvur" || !manifest || !structure) {
    return fail("no-gitvur", "This repository hasn't been indexed yet");
  }
  if (state === "schema-invalid") {
    return fail(
      "schema-invalid",
      ".gitvur/structure.json doesn't match the expected format",
      "unknown field `nodez`, expected one of `nodes`, `edges`, `unresolvedCalls` at line 2 column 9",
    );
  }
  const structureOnly = state === "structure-only";
  const result: RepoBundle = {
    root: `/mock/fixtures/${fixture}`,
    manifest,
    structure,
    annotations: structureOnly
      ? null
      : ((file(fixture, "annotations.json") as Annotations | undefined) ?? null),
    report: structureOnly ? null : ((file(fixture, "report.json") as Report | undefined) ?? null),
    warnings: structureOnly
      ? [
          {
            code: "annotations-missing",
            message: "No descriptions yet: .gitvur/annotations.json is missing",
          },
          { code: "report-missing", message: "Not validated yet: .gitvur/report.json is missing" },
        ]
      : [],
  };
  if (
    state === "architecture" ||
    state === "architecture-stale" ||
    state === "architecture-nested"
  ) {
    const architecture = structuredClone(mockArchitecture) as NonNullable<
      Annotations["architecture"]
    >;
    if (state === "architecture-nested" && architecture.components[1])
      architecture.components[1].parent = "arch:entry";
    result.annotations = {
      ...(result.annotations ?? { modules: [], descriptions: [], edges: [] }),
      architecture,
    };
    result.architectureIssues =
      state === "architecture-stale"
        ? [
            {
              id: "arch:service",
              code: "architecture-stale",
              severity: "warning",
              message: "Source changed",
            },
          ]
        : [];
  }
  if (state === "trust") return Promise.resolve(trustBundle(result));
  if (state === "report-stale" && result.report) {
    result.report = { ...result.report, commitSha: "1a2b3c4" };
    result.warnings.push({
      code: "report-stale",
      message: "The report is older than the structure; validate again",
    });
  }
  if ((state === "flow-stale" || state === "flow-broken") && fixture === "py-flows") {
    return Promise.resolve(flowStateBundle(result, state));
  }
  return Promise.resolve(result);
}

/**
 * `?state=flow-stale`: step 2 of "CLI places an order" was written against older code.
 * `?state=flow-broken`: step 3 of "HTTP order request" points at a deleted function.
 * Only this in-memory copy changes, with the report the validator would write for it.
 */
function flowStateBundle(result: RepoBundle, which: "flow-stale" | "flow-broken"): RepoBundle {
  const annotations = structuredClone(result.annotations);
  const report = structuredClone(result.report);
  const flowId = which === "flow-stale" ? "flow:cli-places-order" : "flow:http-order-request";
  const flow = annotations?.flows?.find((f) => f.id === flowId);
  const status = report?.flows?.find((f) => f.id === flowId);
  if (!annotations || !report || !flow || !status) return result;
  if (which === "flow-stale") {
    const step = flow.steps[1];
    if (step) step.basedOnHash = `sha256:${"0".repeat(64)}`;
    Object.assign(status, { status: "stale", staleSteps: ["s2"] });
  } else {
    const step = flow.steps[2];
    if (step) step.node = "function:flowapp/domain/rules.py:check";
    Object.assign(status, { status: "broken", staleSteps: [] });
    const message =
      "flow `flow:http-order-request` step `s3` refers to `function:flowapp/domain/rules.py:check`, which is not a file, class or function in the structure";
    report.issues.push({ severity: "error", code: "flow-dangling-step", message, id: flowId });
    report.summary = { ...report.summary, errors: report.summary.errors + 1 };
  }
  return { ...result, annotations, report };
}

const never = () => new Promise<never>(() => undefined);

const traces = mockTraces as unknown as Record<string, Trace>;

interface MockDiff {
  commits: CommitInfo[];
  bundle: DiffBundle;
  /** Files of revision A whose text differs from the fixture. */
  fromSources: Record<string, string>;
}
const diffData = mockDiff as unknown as MockDiff;

function sliceOf(
  relpath: string,
  text: string,
  start: number,
  end: number,
  context: number,
): SourceSlice {
  const all = text.replace(/\n$/, "").split("\n");
  const first = Math.min(Math.max(1, start - context), all.length);
  const last = Math.min(all.length, end + context, first + 1999);
  return {
    file: relpath,
    startLine: first,
    lines: all.slice(first - 1, last),
    language: relpath.endsWith(".py")
      ? "python"
      : relpath.endsWith(".ts")
        ? "typescript"
        : /\.[ch]$/.test(relpath)
          ? "c"
          : relpath.endsWith(".go")
            ? "go"
            : "text",
  };
}

export const mockApi: Api = {
  listDocs(path) {
    const fixture = path.split("/").at(-1) ?? fixtureOf(path);
    const prefix = `${PREFIX}${fixture}/`;
    const docs = Object.entries(markdownFiles)
      .filter(([p]) => p.startsWith(prefix))
      .map(([p, text]) => ({
        path: p.slice(prefix.length),
        title: /^# (.+)$/m.exec(text)?.[1] ?? p.split("/").at(-1) ?? p,
        sizeBytes: new TextEncoder().encode(text).length,
        modified: "1793350800",
      }));
    if (params.get("docs") === "unsafe")
      docs.unshift({
        path: "unsafe.md",
        title: "Untrusted document",
        sizeBytes: unsafeDoc.length,
        modified: "1793350800",
      });
    const rank = (p: string) => (p === "README.md" ? 0 : /^(docs|doc)\//.test(p) ? 1 : 2);
    return Promise.resolve(
      docs.sort((a, b) => rank(a.path) - rank(b.path) || a.path.localeCompare(b.path)),
    );
  },
  readDoc(path, docPath) {
    const fixture = path.split("/").at(-1) ?? fixtureOf(path);
    const text =
      params.get("docs") === "unsafe" && docPath === "unsafe.md"
        ? unsafeDoc
        : markdownFiles[`${PREFIX}${fixture}/${docPath}`];
    if (text === undefined || params.get("docMissing") === docPath)
      return fail("io", "document no longer exists");
    return Promise.resolve({
      path: docPath,
      text: text.slice(0, 2 * 1024 * 1024),
      truncated: text.length > 2 * 1024 * 1024,
    });
  },
  readDocAsset(path, docPath, href) {
    const fixture = path.split("/").at(-1) ?? fixtureOf(path);
    const target = localPath(docPath, href);
    const dataUrl = target === null ? undefined : imageFiles[`${PREFIX}${fixture}/${target}`];
    if (!dataUrl) return fail("path-escape", "Image outside the repository was not loaded");
    return Promise.resolve({ mime: "image/svg+xml", dataUrl });
  },
  openExternal(url) {
    document.documentElement.dataset.openedExternal = url;
    return Promise.resolve();
  },
  pickFolder: () => Promise.resolve(`mock://${params.get("fixture") ?? "py-small"}`),
  openRepository: bundle,
  indexRepository: (path) => (state === "indexing" ? never() : bundle(path)),
  validateRepository: bundle,
  readSource(path, relpath, start, end, context): Promise<SourceSlice> {
    const text =
      relpath === missing ? undefined : sources[`${PREFIX}${fixtureOf(path)}/${relpath}`];
    if (text === undefined) return fail("io", `cannot open \`${relpath}\``);
    return Promise.resolve(sliceOf(relpath, text, start, end, context));
  },
  listCommits: (path) =>
    fixtureOf(path) === "py-small" ? Promise.resolve(diffData.commits) : Promise.resolve([]),
  diffRevisions(path) {
    if (fixtureOf(path) !== "py-small") return fail("io", "No history in this mock repository");
    return Promise.resolve(diffData.bundle);
  },
  readRevisionSource(path, rev, relpath, start, end, context) {
    const old = rev === diffData.bundle.diff.fromCommit ? diffData.fromSources[relpath] : undefined;
    if (old !== undefined) return Promise.resolve(sliceOf(relpath, old, start, end, context));
    return mockApi.readSource(path, relpath, start, end, context);
  },
  saveExport(_repo, name, kind, data) {
    // Browser mock: a download stands in for the save dialog.
    const a = document.createElement("a");
    a.href = `data:${kind === "png" ? "image/png" : "image/svg+xml"};base64,${data}`;
    a.download = name;
    a.click();
    return Promise.resolve(true);
  },
  getTrace(path, start) {
    const trace = traces[`${fixtureOf(path)}|${start}`];
    return Promise.resolve(
      trace ?? {
        start,
        roots: [],
        nodes: [],
        truncated: false,
        hiddenRoots: 0,
        error: `unknown entry or node: ${start}`,
      },
    );
  },
  recentRepositories: () =>
    Promise.resolve([
      { path: "mock://py-small", name: "py-small", openedAt: 0 },
      { path: "mock://ts-small", name: "ts-small", openedAt: 0 },
    ]),
  getSettings() {
    try {
      const saved = window.localStorage.getItem(SETTINGS_KEY);
      const fresh = { ...DEFAULT_SETTINGS, guideSeen: params.get("firstrun") !== "1" };
      return Promise.resolve(
        saved ? { ...fresh, ...(JSON.parse(saved) as Partial<Settings>) } : fresh,
      );
    } catch {
      return Promise.resolve(DEFAULT_SETTINGS);
    }
  },
  setSettings(settings) {
    try {
      window.localStorage.setItem(SETTINGS_KEY, JSON.stringify(settings));
    } catch {
      // Storage unavailable (private mode): settings just aren't remembered.
    }
    return Promise.resolve();
  },
  forgetRecent: () => Promise.resolve(),
  getViewState(root) {
    try {
      const saved = window.localStorage.getItem(VIEW_KEY + root);
      return Promise.resolve(saved ? (JSON.parse(saved) as ViewState) : null);
    } catch {
      return Promise.resolve(null);
    }
  },
  setViewState(root, view) {
    try {
      window.localStorage.setItem(VIEW_KEY + root, JSON.stringify(view));
    } catch {
      // Storage unavailable: the view just isn't remembered.
    }
    return Promise.resolve();
  },
  clearViewState(root) {
    try {
      window.localStorage.removeItem(VIEW_KEY + root);
    } catch {
      // Nothing to clear.
    }
    return Promise.resolve();
  },
  setTitle(title) {
    document.title = title;
    return Promise.resolve();
  },
  initialPath() {
    const fixture = params.get("fixture");
    return fixture ? `mock://${fixture}` : null;
  },
};

//! TypeScript bindings for the contract and the app's command types, generated with ts-rs
//! into `app/src/generated/contract.ts`. A test fails when the committed file is out of
//! date; regenerate with `GITVUR_WRITE_BINDINGS=1 cargo test -p gitvur-app bindings`
//! (or `pnpm gen:types` from `app/`).

use ts_rs::{Config, TS};

use crate::bundle::{RepoBundle, SourceLanguage, SourceSlice};
use crate::diffs::{CommitInfo, DiffBundle};
use crate::docs::{AssetData, DocContent, DocEntry};
use crate::error::{AppError, AppWarning, ErrorCode, WarningCode};
use crate::settings::{RecentRepo, Settings, Theme, ViewState, Viewport};

macro_rules! declarations {
    ($cfg:expr; $($t:ty),* $(,)?) => {
        vec![$(format!("export {}", <$t as TS>::decl($cfg))),*]
    };
}

/// The full contents of `contract.ts`.
pub fn typescript() -> String {
    use gitvur_schema as s;
    let cfg = Config::default();
    let decls = declarations![&cfg;
        // Contract v0.3 (gitvur-schema)
        s::Manifest, s::ExtractorInfo, s::Language,
        s::Structure, s::Node, s::NodeType, s::UnresolvedCall,
        s::Trace, s::TraceNode, s::TraceKind,
        s::EntryPoint, s::EntryKind, s::Flow, s::FlowStep, s::FlowTransition, s::TransitionKind, s::FlowStatus, s::FlowState,
        s::Edge, s::EdgeType, s::Provenance, s::Evidence, s::SourceRange,
        s::ArchitectureArtifact, s::Architecture, s::ArchitectureComponent, s::ArchitectureSource, s::ArchitectureRelationship,
        s::Annotations, s::Module, s::Description,
        s::Report, s::Summary, s::ElementStatus, s::Status, s::Issue, s::Severity,
        s::StructureDiff, s::ChangeKind, s::ElementChange, s::EdgeChange, s::DiffSummary,
        // App commands (gitvur-app)
        RepoBundle, AppWarning, WarningCode, AppError, ErrorCode,
        SourceSlice, SourceLanguage, RecentRepo, Settings, Theme,
        CommitInfo, DiffBundle, ViewState, Viewport, DocEntry, DocContent, AssetData,
    ];
    let mut out = String::from(
        "// Generated by ts-rs from the Rust types in gitvur-schema and gitvur-app.\n\
         // Do not edit by hand: run `pnpm gen:types` from app/.\n\n",
    );
    for decl in decls {
        out.push_str(
            &decl
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n"),
        );
        out.push_str("\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    #[test]
    fn bindings_are_up_to_date() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/generated/contract.ts");
        let expected = super::typescript();
        if std::env::var_os("GITVUR_WRITE_BINDINGS").is_some() {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, &expected).unwrap();
        }
        let actual = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            actual == expected,
            "app/src/generated/contract.ts is out of date; run `pnpm gen:types` from app/"
        );
    }
}
